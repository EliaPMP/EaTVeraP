export type WaterType = "bottled" | "filtered" | "tap" | "sparkling";

export interface WaterProduct {
  id: string;
  name: string;
  brand: string;
  type: WaterType;
  imageUrl?: string;
  category: string;
  qualityScore: number;
  scoreLabel: string;
  ph: number;
  tds: number; // Total Dissolved Solids (ppm)
  source: string;
  minerals: {
    calcium?: number;   // mg/L
    magnesium?: number; // mg/L
    sodium?: number;    // mg/L
    potassium?: number; // mg/L
    bicarbonate?: number; // mg/L
    silica?: number;    // mg/L
    fluoride?: number;  // mg/L
  };
  contaminants: string[];
  certifications: string[];
  healthNotes: string;
  averagePrice?: number;
  warnings: string[];
  plasticType?: string; // BPA-free, PET, glass, etc.
  country: string;
}

function score(s: number): string {
  if (s >= 85) return "Excellent";
  if (s >= 70) return "Good";
  if (s >= 50) return "Fair";
  return "Poor";
}

