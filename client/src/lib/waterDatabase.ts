// ─── HELPER FUNCTIONS ─────────────────────────────────────────────────────────

export const ALL_BOTTLED = ALL_WATERS.filter(w => w.type === "bottled");
export const ALL_SPARKLING = ALL_WATERS.filter(w => w.type === "sparkling");
export const ALL_FILTERED = ALL_WATERS.filter(w => w.type === "filtered");
export const ALL_TAP = ALL_WATERS.filter(w => w.type === "tap");

export function searchWater(query: string): WaterProduct[] {
  const q = query.toLowerCase();
  return ALL_WATERS.filter(
    w =>
      w.name.toLowerCase().includes(q) ||
      w.brand.toLowerCase().includes(q) ||
      w.source.toLowerCase().includes(q) ||
      w.category.toLowerCase().includes(q) ||
      w.country.toLowerCase().includes(q)
  );
}

export function filterByWaterType(type: WaterType | null): WaterProduct[] {
  if (!type) return ALL_WATERS;
  return ALL_WATERS.filter(w => w.type === type);
}

export function getScoreColor(score: number): string {
  if (score >= 85) return "#0B3D2E";
  if (score >= 70) return "#eab308";
  if (score >= 50) return "#f97316";
  return "#dc2626";
}
