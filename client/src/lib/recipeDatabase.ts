/** Get recipes filtered by category */
export function getRecipesByCategory(category: RecipeCategory): Recipe[] {
  return ALL_RECIPES.filter(r => r.category === category);
}

/** Get today's featured recipe (deterministic by day-of-year) */
export function getFeaturedRecipe(): Recipe {
  const featured = ALL_RECIPES.filter(r => r.featured);
  const pool = featured.length > 0 ? featured : ALL_RECIPES;
  const dayOfYear = Math.floor((Date.now() - new Date(new Date().getFullYear(), 0, 0).getTime()) / 86400000);
  return pool[dayOfYear % pool.length];
}

/** Get recipes recommended for a user based on their goal alignment */
export function getRecommendedRecipes(goals: string[], limit = 6): Recipe[] {
  const scored = ALL_RECIPES.map(r => ({
    recipe: r,
    score: r.goalAlignment.filter(g => goals.includes(g)).length,
  }));
  return scored
    .filter(s => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map(s => s.recipe);
}

/** Search recipes by name, ingredient, or tag */
export function searchRecipes(query: string): Recipe[] {
  const q = query.toLowerCase().trim();
  if (!q) return ALL_RECIPES;
  return ALL_RECIPES.filter(r =>
    r.name.toLowerCase().includes(q) ||
    r.description.toLowerCase().includes(q) ||
    r.tags.some(t => t.toLowerCase().includes(q)) ||
    r.ingredients.some(i => i.item.toLowerCase().includes(q))
  );
}
