export function getFruitScore(entry: FruitEntry, organic: boolean): number {
  return organic ? entry.organicScore : entry.conventionalScore;
}

export function getFruitColor(score: number): string {
  if (score >= 85) return "#145A3A";
  if (score >= 70) return "#3FA34D";
  if (score >= 55) return "#65a30d";
  if (score >= 40) return "#d97706";
  if (score >= 25) return "#ea580c";
  return "#dc2626";
}

