/**
 * EatVera — Comprehensive US Fruit Database
 * Quality ratings based on:
 * - EWG Dirty Dozen / Clean Fifteen pesticide data (2024)
 * - USDA Pesticide Data Program residue findings
 * - Nutritional density (vitamins, antioxidants, fiber)
 * - Organic vs conventional availability
 * - Country of origin / sourcing transparency
 * - Processing level (fresh, frozen, canned, dried)
 */

export type FruitQualityTier = "excellent" | "good" | "caution" | "avoid";
export type FruitCategory =
  | "Berries"
  | "Citrus"
  | "Tropical"
  | "Stone Fruit"
  | "Pome Fruit"
  | "Melons"
  | "Grapes & Vine"
  | "Dried Fruit"
  | "Packaged / Canned"
  | "Exotic";

export interface FruitEntry {
  id: string;
  name: string;
  imageUrl?: string;
  category: FruitCategory;
  qualityTier: FruitQualityTier;
  /** EWG pesticide rank: lower = more pesticides. null if not ranked */
  ewgRank: number | null;
  ewgStatus: "dirty-dozen" | "clean-fifteen" | "middle" | "not-ranked";
  /** Conventional score (no organic) */
  conventionalScore: number;
  /** Organic score */
  organicScore: number;
  /** Whether organic is widely available in US stores */
  organicAvailable: boolean;
  pesticides: string;
  nutritionHighlights: string[];
  concerns: string[];
  benefits: string[];
  buyTip: string;
  averagePrice?: number;
  /** Typical US grocery store barcodes / PLU codes */
  pluCodes: string[];
  /** Key nutrients per 100g */
  nutrients: {
    calories?: number;
    carbs?: number;
    fiber?: number;
    sugar?: number;
    protein?: number;
    vitaminC?: number; // mg
    potassium?: number; // mg
    antioxidants?: string;
  };
  season: string;
  origin: string;
}

